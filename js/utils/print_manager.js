    /**
     * Create print window and render content
     */
    function createPrintWindow(html, options) {
        const config = { ...defaults, ...options };
        
        // Create print window
        const printWindow = window.open('', '_blank');
        if (!printWindow) {
            alert('Please allow popups for printing functionality');
            return null;
        }
        
        // Generate complete HTML document
        const printDocument = `
            <!DOCTYPE html>
            <html>
            <head>
                <meta charset="UTF-8">
                <title>${escapeHtml(config.title || 'Print')}</title>
                ${generatePrintCSS(config)}
            </head>
            <body>
                ${html}
                ${generateReportFooter(config)}
            </body>
            </html>
        `;
        
        printWindow.document.write(printDocument);
        printWindow.document.close();
        
        // Wait for content to load, then print
        printWindow.onload = function() {
            setTimeout(() => {
                printWindow.print();
                // Don't close automatically - let user review
                // printWindow.close();
            }, 250);
        };
        
        return printWindow;
    }

    /**
     * Print a table report
     */
    function printTable(options) {
        const config = {
            columns: [],
            rows: [],
            summary: null,
            ...options
        };
        
        if (!config.rows || config.rows.length === 0) {
            alert('No data to print');
            return;
        }
        
        // Generate table HTML
        const tableHtml = `
            <div class="print-table-container">
                <table class="print-table">
                    <thead>
                        <tr>
                            ${config.columns.map(col => 
                                `<th>${escapeHtml(col.label || col)}</th>`
                            ).join('')}
                        </tr>
                    </thead>
                    <tbody>
                        ${config.rows.map((row, index) => `
                            <tr>
                                <td>${index + 1}</td>
                                ${config.columns.slice(1).map(col => 
                                    `<td>${escapeHtml(row[col.key] || row[col] || '')}</td>`
                                ).join('')}
                            </tr>
                        `).join('')}
                    </tbody>
                </table>
            </div>
        `;
        
        // Generate summary if provided
        let summaryHtml = '';
        if (config.summary) {
            summaryHtml = `
                <div class="print-report-summary">
                    <h4>Summary</h4>
                    <div class="print-summary-grid">
                        ${Object.entries(config.summary).map(([key, value]) => `
                            <div class="print-summary-item">
                                <div class="print-summary-label">${escapeHtml(key)}</div>
                                <div class="print-summary-value">${escapeHtml(String(value))}</div>
                            </div>
                        `).join('')}
                    </div>
                </div>
            `;
        }
        
        // Generate complete HTML
        const html = `
            ${generateReportHeader(config)}
            ${summaryHtml}
            ${tableHtml}
        `;
        
        return createPrintWindow(html, config);
    }

    /**
     * Print a record/detail report
     */
    function printRecord(options) {
        const config = {
            sections: [],
            ...options
        };
        
        if (!config.sections || config.sections.length === 0) {
            alert('No data to print');
            return;
        }
        
        // Generate sections HTML
        const sectionsHtml = config.sections.map(section => `
            <div class="print-record-section">
                <h4>${escapeHtml(section.title)}</h4>
                ${section.fields ? section.fields.map(field => `
                    <div class="print-record-row">
                        <div class="print-record-label">${escapeHtml(field.label)}:</div>
                        <div class="print-record-value">${escapeHtml(String(field.value || ''))}</div>
                    </div>
                `).join('') : ''}
                ${section.content ? `<div>${escapeHtml(section.content)}</div>` : ''}
            </div>
        `).join('');
        
        // Generate complete HTML
        const html = `
            ${generateReportHeader(config)}
            ${sectionsHtml}
        `;
        
        return createPrintWindow(html, config);
    }

    /**
     * Print modal content
     */
    function printModal(modalId, options) {
        const modal = document.getElementById(modalId);
        if (!modal) {
            alert('Modal not found');
            return;
        }
        
        // Extract modal content
        const modalBody = modal.querySelector('.modal-body');
        if (!modalBody) {
            alert('Modal body not found');
            return;
        }
        
        const config = {
            title: options.title || modal.querySelector('.modal-title')?.textContent || 'Details',
            ...options
        };
        
        // Clean up modal content for printing
        const content = modalBody.innerHTML
            .replace(/<button[^>]*>.*?<\/button>/gi, '') // Remove buttons
            .replace(/<input[^>]*>/gi, '') // Remove inputs
            .replace(/<select[^>]*>.*?<\/select>/gi, '') // Remove selects
            .replace(/class="[^"]*btn[^"]*"/gi, 'class="print-hidden"') // Mark buttons
            .replace(/class="[^"]*form-control[^"]*"/gi, 'class="print-static"'); // Make forms static
        
        // Generate complete HTML
        const html = `
            ${generateReportHeader(config)}
            <div class="print-record-section">
                ${content}
            </div>
        `;
        
        return createPrintWindow(html, config);
    }

